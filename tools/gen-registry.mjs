// Regenerates src/game/registry.ts: every module whose classes the save system may need.
import fs from "fs";
import path from "path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const game = path.join(root, "src/game");
const mods = [];
const walk = (d) => {
    for (const f of fs.readdirSync(d, { withFileTypes: true })) {
        const p = path.join(d, f.name);
        if (f.isDirectory()) { if (!["ui", "runtime", "save", "data"].includes(f.name)) walk(p); }
        else if (f.name.endsWith(".ts") && f.name !== "registry.ts") mods.push(path.relative(game, p).replace(/\\/g, "/").slice(0, -3));
    }
};
walk(game);
mods.sort();
let out = "// AUTO-GENERATED by tools/gen-registry.mjs — every class the save system may need to rebuild.\n";
out += 'import * as RT from "./runtime";\n';
mods.forEach((m, i) => (out += `import * as M${i} from "./${m}";\n`));
out += "/** Built on first use (not at import time) so import cycles can't leave entries undefined. */\n";
out += "export function allClasses(): Record<string, any> {\n    return Object.assign({},\n";
out += "        { ArrayList: RT.ArrayList, HashMap: RT.HashMap, HashSet: RT.HashSet, Pair: RT.Pair, Triple: RT.Triple, BigInteger: RT.BigInteger, SpannableStringBuilder: RT.SpannableStringBuilder },\n";
mods.forEach((_, i) => (out += `        M${i},\n`));
out += "    );\n}\n";
const target = path.join(game, "registry.ts");
if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== out) fs.writeFileSync(target, out);
console.log(`registry: ${mods.length} modules`);
